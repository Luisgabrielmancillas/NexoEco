import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const source = JSON.parse(readFileSync(new URL('../resources/design-system/tokens.json', import.meta.url), 'utf8'));
const resolve = (name, seen = new Set()) => {
    if (seen.has(name) || !source.colors[name]) throw new Error(`Invalid color token: ${name}`);
    const value = source.colors[name];
    return value.startsWith('{') ? resolve(value.slice(1, -1), new Set([...seen, name])) : value;
};
const declarations = Object.entries(source.colors).flatMap(([name, value]) => {
    const hex = resolve(name);
    if (!/^#[\da-f]{6}$/i.test(hex)) throw new Error(`Invalid hex color: ${name}`);
    const channels = [1, 3, 5].map(index => parseInt(hex.slice(index, index + 2), 16)).join(' ');
    return [`    --color-${name}: ${value.startsWith('{') ? `var(--color-${value.slice(1, -1)})` : hex};`, `    --color-${name}-rgb: ${channels};`];
});
for (const [alias, name] of Object.entries(source.aliases)) {
    resolve(name);
    declarations.push(`    --${alias}: var(--color-${name});`);
}
const output = `/* Generated by scripts/build-design-tokens.mjs. Edit resources/design-system/tokens.json. */\n:root {\n${declarations.join('\n')}\n}\n`;
const path = new URL('../resources/css/design-tokens.css', import.meta.url);
const iconPath = new URL('../public/favicon.svg', import.meta.url);
const icon = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 80 80"><path d="M20 40 40 20 60 40H48V60H32V40Z" fill="${resolve('primary')}" transform="rotate(45 40 40)"/><path d="M20 40 40 20 60 40H48V60H32V40Z" fill="${resolve('surface')}" stroke="${resolve('primary')}" stroke-width="3" transform="rotate(225 40 40)"/></svg>\n`;
if (process.argv.includes('--check')) {
    if (readFileSync(path, 'utf8') !== output) throw new Error('Design tokens are out of date. Run npm run tokens.');
    if (readFileSync(iconPath, 'utf8') !== icon) throw new Error('Brand icon is out of date. Run npm run tokens.');
} else {
    writeFileSync(path, output);
    writeFileSync(iconPath, icon);
}
console.log(`Design tokens ${process.argv.includes('--check') ? 'verified' : 'generated'}: ${Object.keys(source.colors).length} colors (${fileURLToPath(path)}).`);
